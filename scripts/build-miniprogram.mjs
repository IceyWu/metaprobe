import { mkdir, readFile, writeFile, copyFile } from 'node:fs/promises'

const source = await readFile(new URL('../wasm/index.js', import.meta.url), 'utf8')
const boundary = source.indexOf('\nasync function __wbg_load(')
if (boundary < 0 || !source.includes('function __wbg_get_imports()') || !source.includes('function __wbg_finalize_init(')) {
  throw new Error('Unsupported wasm-bindgen output: review the mini-program adapter before building.')
}
// Keep generated ABI/imports; replace the browser loader and supply local UTF-8 codecs.
const glue = `// Generated by scripts/build-miniprogram.mjs. Do not edit.
import { Utf8Encoder as TextEncoder, Utf8Decoder as TextDecoder } from './utf8.js';
${source.slice(0, boundary)}
export async function instantiate(runtime, path) {
    const result = await runtime.instantiate(path, __wbg_get_imports());
    const instance = result.instance || result;
    if (!instance.exports || !instance.exports.memory) {
        throw new Error('WXWebAssembly returned an invalid metaprobe instance');
    }
    return __wbg_finalize_init(instance, result.module);
}
`
if (/\b(?:fetch|WebAssembly|document|window)\b|import\.meta/.test(glue)) {
  throw new Error('Browser runtime dependency leaked into mini-program glue.')
}
await mkdir(new URL('../miniprogram/', import.meta.url), { recursive: true })
await writeFile(new URL('../miniprogram/glue.js', import.meta.url), glue)
await copyFile(new URL('../src/miniprogram/glue.d.ts', import.meta.url), new URL('../miniprogram/glue.d.ts', import.meta.url))
await copyFile(new URL('../wasm/index_bg.wasm', import.meta.url), new URL('../miniprogram/index_bg.wasm', import.meta.url))
// wasm-pack writes a wildcard .gitignore; override it for npm's package walker.
await writeFile(new URL('../wasm/.npmignore', import.meta.url), '')
console.log('Mini-program WASM and glue generated.')
